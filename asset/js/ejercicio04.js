// Datos de entrada
// Constantes
const nota1 = 4.5;
const nota2 = 3.8;
const nota3 = 2.9;
const nota4 = 4.0;


//proceso 
// Calcular la suma de las 4 notas
let suma = nota1 + nota2 + nota3 + nota4;
// Calcular el promedio 
let promedio = suma / 4;
// Calcular el resultado de la expresión
let resultadoExpresion = (nota1 + nota2) * (nota3 + nota4) / 2;

// Datos de salida 
alert("Suma de las 4 notas: " + suma + "\n" + 
    "Promedio:  " + promedio + "\n" + 
    "Resultado de la operación:  " + resultadoExpresion + "\n" )